if (Test-Path $overrideFile) {
  $existingOverride = Get-Content $overrideFile -Raw
  if ($existingOverride.StartsWith($generatedOverrideHeader)) {
    Remove-Item $overrideFile -Force
  } elseif ($existingOverride -match 'naza_windows_litertlm') {
    Remove-Item $overrideFile -Force
  } else {
    throw "pubspec_overrides.yaml already exists and was not generated by NAZA tooling: $overrideFile"
  }
}

Invoke-Checked $Flutter @('pub', 'get')
if (-not (Test-Path $packageConfig)) { throw '.dart_tool/package_config.json was not generated.' }
$config = Get-Content $packageConfig -Raw | ConvertFrom-Json
$entry = $config.packages | Where-Object { $_.name -eq 'flutter_gemma_litertlm' } | Select-Object -First 1
if (-not $entry) { throw 'flutter_gemma_litertlm is missing from package_config.json.' }
$rootUri = [Uri]$entry.rootUri
if (-not $rootUri.IsAbsoluteUri) {
  $configUri = [Uri](Resolve-Path $packageConfig).Path
  $rootUri = [Uri]::new($configUri, $rootUri)
}
$sourcePackageDir = $rootUri.LocalPath
$sourcePubspec = Get-Content (Join-Path $sourcePackageDir 'pubspec.yaml') -Raw
if ($sourcePubspec -notmatch '(?m)^version:\s*1\.3\.1\s*$') {
  throw "Expected flutter_gemma_litertlm $bridgeVersion before Windows preparation."
}

Remove-Item $localPackageDir -Recurse -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force -Path $localPackageDir | Out-Null
Copy-Item (Join-Path $sourcePackageDir '*') $localPackageDir -Recurse -Force

$enginePath = Join-Path $localPackageDir 'lib\src\litert_lm_engine.dart'
$engineText = Get-Content $enginePath -Raw
$cacheNeedle = 'final cacheDir = (await getApplicationSupportDirectory()).path;'
$cacheReplacement = "final cacheDir = ':nocache'; // NAZA Windows: avoid Gemma 4 MTP cache collision (#2572)"
if ($engineText.Contains($cacheNeedle)) {
  $engineText = $engineText.Replace($cacheNeedle, $cacheReplacement)
  Set-Content $enginePath $engineText -Encoding utf8
} elseif ($engineText -notmatch "cacheDir = ':nocache'") {
  throw 'Modern bridge cacheDir source shape changed; refusing a blind patch.'
}

@"
$generatedOverrideHeader
dependency_overrides:
  flutter_gemma_litertlm:
    path: .dart_tool/naza_windows_litertlm_1_3_1
"@ | Set-Content $overrideFile -Encoding utf8
Invoke-Checked $Flutter @('pub', 'get')

$localPubspec = Get-Content (Join-Path $localPackageDir 'pubspec.yaml') -Raw
$hookPath = Join-Path $localPackageDir 'hook\build.dart'
$hookText = Get-Content $hookPath -Raw
if ($localPubspec -notmatch '(?m)^version:\s*1\.3\.1\s*$') { throw 'Local Windows bridge is not 1.3.1.' }
if ($hookText -notmatch "version:\s*'0\.14\.0'") {
  throw 'flutter_gemma_litertlm 1.3.1 native hook no longer declares the expected modern 0.14.0 baseline.'
}

if ($SkipNativeBuild) {
  Write-Host 'Skipping native source build by request.' -ForegroundColor Yellow
  exit 0
}

$BazelCommand = Get-Command 'bazelisk' -ErrorAction SilentlyContinue
if (-not $BazelCommand) { $BazelCommand = Get-Command 'bazel' -ErrorAction SilentlyContinue }
if (-not $BazelCommand) {
  throw 'Bazelisk/Bazel is required. Recommended on Windows: winget install --id=Bazel.Bazelisk -e'
}
$Bazel = $BazelCommand.Source

Ensure-DetachedCheckout $Git $LiteRtLmRepo $LiteRtLmRef $sourceRoot
Invoke-Checked $Git @('lfs', 'install', '--local') $sourceRoot
Invoke-Checked $Git @('lfs', 'pull', '--include=prebuilt/windows_x86_64/*') $sourceRoot

$versionText = Get-Content (Join-Path $sourceRoot 'version.bzl') -Raw
if ($versionText -notmatch 'VERSION\s*=\s*"0\.16\.0"') {
  throw "Pinned LiteRT-LM source is no longer the expected $expectedLiteRtLmVersion development line."
}
$workspaceText = Get-Content (Join-Path $sourceRoot 'WORKSPACE') -Raw
if ($workspaceText -notmatch [regex]::Escape("LITERT_REF = `"$LiteRtRef`"")) {
  throw 'LiteRT-LM WORKSPACE LiteRT pin does not match the NAZA provenance pin.'
}

$patchPath = Join-Path $sourceRoot 'PATCH.litert_windows_nvidia_webgpu_upload'
if (-not (Test-Path $patchPath)) { throw "Windows WebGPU patch is missing: $patchPath" }

Ensure-DetachedCheckout $Git 'https://github.com/google-ai-edge/LiteRT.git' $LiteRtRef $liteRtRoot
Invoke-Checked $Git @('clean', '-fdx') $liteRtRoot
Invoke-Checked $Git @('reset', '--hard', $LiteRtRef) $liteRtRoot
Invoke-Checked $Git @('apply', '--check', $patchPath) $liteRtRoot
Invoke-Checked $Git @('apply', $patchPath) $liteRtRoot

$override = $liteRtRoot.Replace('\', '/')
$commonArgs = @(
  '--config=windows',
  '--define=litert_runtime_link_mode=dynamic',
  '--define=resolve_symbols_in_exec=false',
  "--override_repository=litert=$override"
)
$cApiTarget = '//c:litert-lm'
$acceleratorTarget = '@litert//litert/runtime/accelerators/gpu:libLiteRtWebGpuAccelerator'
Invoke-Checked $Bazel (@('build') + $commonArgs + @($cApiTarget, $acceleratorTarget)) $sourceRoot

$cApiDll = Resolve-BazelDll $Bazel $commonArgs $cApiTarget $sourceRoot
$acceleratorDll = Resolve-BazelDll $Bazel $commonArgs $acceleratorTarget $sourceRoot

Remove-Item $bundleRoot -Recurse -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force -Path $bundleRoot | Out-Null
$prebuiltRoot = Join-Path $sourceRoot 'prebuilt\windows_x86_64'
