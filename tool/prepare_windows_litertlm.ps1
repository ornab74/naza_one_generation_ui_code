$Flutter = Require-Command 'flutter'

Write-Host '=== NAZA One modern Windows LiteRT-LM preparation ===' -ForegroundColor Green
Write-Host "Dart bridge       : flutter_gemma_litertlm $bridgeVersion"
Write-Host "LiteRT-LM source  : $LiteRtLmRepo @ $LiteRtLmRef"
