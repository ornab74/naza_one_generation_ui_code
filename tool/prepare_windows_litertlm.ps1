function Require-Command([string]$Name) {
  $cmd = Get-Command $Name -ErrorAction SilentlyContinue
  if (-not $cmd) { throw "Required command '$Name' was not found in PATH." }
  return $cmd.Source
}

function Invoke-Checked([string]$Exe, [string[]]$Args, [string]$WorkingDirectory = $repoRoot) {
  Write-Host "> $Exe $($Args -join ' ')" -ForegroundColor Cyan
  Push-Location $WorkingDirectory
  try {
    & $Exe @Args
    if ($LASTEXITCODE -ne 0) {
      throw "Command failed with exit code ${LASTEXITCODE}: $Exe $($Args -join ' ')"
    }
  } finally {
    Pop-Location
  }
}

function Resolve-BazelDll([string]$Bazel, [string[]]$CommonArgs, [string]$Target, [string]$WorkingDirectory) {
  Push-Location $WorkingDirectory
  try {
    $lines = & $Bazel cquery @CommonArgs $Target '--output=files'
    if ($LASTEXITCODE -ne 0) { throw "bazel cquery failed for $Target" }
  } finally {
    Pop-Location
  }
  $candidate = $lines | Where-Object { $_ -and $_.Trim().ToLowerInvariant().EndsWith('.dll') } | Select-Object -First 1
  if (-not $candidate) { throw "Could not resolve DLL output for $Target. Output: $($lines -join '; ')" }
  if ([IO.Path]::IsPathRooted($candidate)) { return (Resolve-Path $candidate).Path }
  return (Resolve-Path (Join-Path $WorkingDirectory $candidate)).Path
}

function Assert-NotLfsPointer([string]$Path) {
  if (-not (Test-Path $Path)) { throw "Required runtime file is missing: $Path" }
  $firstLine = Get-Content $Path -TotalCount 1 -ErrorAction Stop
  if ($firstLine -eq 'version https://git-lfs.github.com/spec/v1') {
    throw "Git LFS file is still a pointer: $Path"
  }
}

function Ensure-DetachedCheckout([string]$Git, [string]$Url, [string]$Ref, [string]$Directory) {
  if (-not (Test-Path (Join-Path $Directory '.git'))) {
    if (Test-Path $Directory) { Remove-Item $Directory -Recurse -Force }
    Invoke-Checked $Git @('clone', '--filter=blob:none', '--no-checkout', $Url, $Directory) $repoRoot
  }
  Invoke-Checked $Git @('fetch', '--depth=1', 'origin', $Ref) $Directory
  Invoke-Checked $Git @('checkout', '--detach', $Ref) $Directory
  Invoke-Checked $Git @('reset', '--hard', $Ref) $Directory
}

