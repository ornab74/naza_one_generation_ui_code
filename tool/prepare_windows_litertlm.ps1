  Assert-NotLfsPointer $_.FullName
  Copy-Item $_.FullName $bundleRoot -Force
}

Copy-Item $cApiDll (Join-Path $bundleRoot 'LiteRtLm.dll') -Force
Copy-Item $acceleratorDll (Join-Path $bundleRoot 'libLiteRtWebGpuAccelerator.dll') -Force

$aliases = [ordered]@{
  'libGemmaModelConstraintProvider.dll' = 'GemmaModelConstraintProvider.dll'
  'libLiteRt.dll' = 'LiteRt.dll'
  'libLiteRtTopKWebGpuSampler.dll' = 'LiteRtTopKWebGpuSampler.dll'
  'libLiteRtWebGpuAccelerator.dll' = 'LiteRtWebGpuAccelerator.dll'
  'libwebgpu_dawn.dll' = 'webgpu_dawn.dll'
}
foreach ($pair in $aliases.GetEnumerator()) {
  $src = Join-Path $bundleRoot $pair.Key
  if (Test-Path $src) { Copy-Item $src (Join-Path $bundleRoot $pair.Value) -Force }
}

$acceleratorOut = Join-Path $bundleRoot 'libLiteRtWebGpuAccelerator.dll'
$cApiOut = Join-Path $bundleRoot 'LiteRtLm.dll'
Assert-NotLfsPointer $acceleratorOut
Assert-NotLfsPointer $cApiOut

$hashes = [ordered]@{}
Get-ChildItem $bundleRoot -Filter '*.dll' | Sort-Object Name | ForEach-Object {
  $hashes[$_.Name] = (Get-FileHash $_.FullName -Algorithm SHA256).Hash.ToLowerInvariant()
}

$marker = [ordered]@{
  schema = 'naza-windows-litertlm-modern-v1'
  flutter_gemma_litertlm = $bridgeVersion
  flutter_native_baseline = '0.14.0'
  litert_lm_source_version = $expectedLiteRtLmVersion
  litert_lm_repo = $LiteRtLmRepo
  litert_lm_ref = $LiteRtLmRef
  litert_ref = $LiteRtRef
  litert_c_api_version = '0.1.0'
  windows_webgpu_weight_upload = 'serialized'
  windows_gpu_compute = 'enabled'
  windows_gpu_cache = ':nocache'
  c_api_target = $cApiTarget
  accelerator_target = $acceleratorTarget
  c_api_sha256 = $hashes['LiteRtLm.dll']
  accelerator_sha256 = $hashes['libLiteRtWebGpuAccelerator.dll']
