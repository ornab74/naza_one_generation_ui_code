  [string]$LiteRtLmRef = '6eeeb1d1195ee83f00e96da82ba1ed63e328063a',
  [string]$LiteRtRef = 'b0f6c12088df229f6342f1af164caa66ffa7b010',
  [switch]$SkipNativeBuild
